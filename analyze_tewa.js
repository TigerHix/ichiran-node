import { analyze } from './packages/grammar/src/engine/index.js';

const sentences = [
  'そのように力を入れて回してはネジがだめになってしまいますよ。',
  'そんなに長くては鞄に入らないので、半分に折ってください。',
  '私は掃除が苦手なので、そんな几帳面では私と住むことはできないでしょう。',
  'そんな貧乏くさい格好ではあのレストランには入れないよ。',
  'リーダーがあの人じゃ嫌です。',
  'ご飯を全部食べなくちゃ大きくなれないよ。',
  'このような間違いを何回もしていては、夏休みの課題はやりきれない。',
  'そのような振る舞いでは、周囲はあなたを「馬鹿な人」と評価し、誰もあなたに対して真面目に相手をしないでしょう。',
  '寝る前にそんなコーヒーを飲んでは寝られない。',
  '無理に引っぱっては壊れてしまいますよ！',
  '今シーズンの結果次第では、引退もあると思いますよ。',
  'こんなに塩辛くては売り物にならないよ。',
  'そんな服装ではあの店には入れてもらえないよ。',
  'そのような給与では、あの工場で働くには無理がある。',
  'ガソリンがこんなに高くては、車で通勤できないだろうね。自転車などを使うしかない。',
  'ポーランドの悪天候のため、オウムを解放しては、必ず死んでしまうでしょう。',
  'あの先生じゃ、無理。去年、生徒全員が試験に落ちたんだ。',
  'ピザのパン生地がどろどろになるよ、水があまりに多くては。。。',
];

for (const sent of sentences) {
  console.log('\n========================================');
  console.log(`Sentence: ${sent}`);
  console.log('========================================');
  const doc = await analyze(sent);

  doc.tokens.forEach((t, i) => {
    console.log(`${i}: ${JSON.stringify({
      text: t.text,
      lemma: t.lemma,
      pos: t.pos,
      dep: t.dep,
      head: t.head,
      inflectionForm: t.inflectionForm,
    })}`);
  });
}
